void InitLanguage() {
    const int l = Cfg().language;
    g_lang = (l >= 0 && l < static_cast<int>(Lang::Count)) ? static_cast<Lang>(l) : Lang::En;
}

Lang CurrentLanguage() { return g_lang; }

const wchar_t* LanguageName(Lang l) {
    switch (l) {
        case Lang::Uk: return L"Українська";
        case Lang::Es: return L"Español";
        default:       return L"English";
    }
}

const wchar_t* T(Str id) {
    return kStrings[static_cast<int>(id)][static_cast<int>(g_lang)];
}
